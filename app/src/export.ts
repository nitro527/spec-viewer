const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
  .replace(/"/g, "&quot;").replace(/'/g, "&#39;");

async function inlineAssets(html: string): Promise<string> {
  const urls = [...new Set([...html.matchAll(/src="(\/api\/asset\/[0-9a-f]+)"/g)].map((m) => m[1]))];
  const map = new Map<string, string>();
  await Promise.all(urls.map(async (u) => {
    const blob = await (await fetch(u)).blob();
    const data = await new Promise<string>((res) => { const r = new FileReader(); r.onload = () => res(String(r.result)); r.readAsDataURL(blob); });
    map.set(u, data);
  }));
  // files open without the app's CSP: always the full pass
  return safeHtml(html, true).replace(/src="(\/api\/asset\/[0-9a-f]+)"/g, (_, u) => `src="${map.get(u) ?? u}"`);
}

export async function compareReport(data: CompareResult): Promise<string> {
  const crRows = data.crs.map((c) => `<tr><td>${c.new_version}</td><td>${esc(c.cr)}${c.rev && c.rev !== "-" ? ` r${esc(c.rev)}` : ""}</td>
    <td>${esc(c.cat)}</td><td>${esc(c.tdoc)}</td><td>${esc(c.subject)}</td>
    <td>${c.detail ? esc(c.detail.clauses_raw) : ""}</td></tr>`).join("");
  const clauses = [...data.clauses, ...data.removed].map((c) => {
    const blocks = c.blocks.filter((b) => b.op !== "equal").map((b) => {
      const tag = b.op === "move-in" ? `<div class="mv">↘ moved from §${esc(b.moved_from ?? "")}</div>`
        : b.op === "move-out" ? `<div class="mv">↗ moved to §${esc(b.moved_to ?? "")}</div>` : "";
      return `<div class="blk">${tag}${b.op === "move-out" ? `<del>${b.old ?? ""}</del>` : b.diff}</div>`;
    }).join("");
    return `<section><h3>${esc(c.number)} ${esc(c.title)} <small>${c.status}</small></h3>${blocks}</section>`;
  }).join("\n");
  const body = await inlineAssets(clauses);
  return `<!doctype html><html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>TS ${esc(data.spec)} v${data.old} → v${data.new}</title>
${KATEX_CSS}
<style>
body{font:15px/1.5 "Times New Roman",serif;max-width:1000px;margin:24px auto;padding:0 16px;color:#1d1d1b}
h1,h2,h3{font-family:system-ui,sans-serif}h3 small{font-weight:normal;color:#777;font-size:12px}
table{border-collapse:collapse;font:12.5px Arial,sans-serif}td,th{border:1px solid #ccc;padding:3px 6px;vertical-align:top}
ins{background:#d9f5dc;color:#0f5a1c;text-decoration:none}del{background:#fde0dd;color:#8a1c12}
.blk{margin:6px 0;padding-left:8px;border-left:3px solid #e0c060}.mv{font:12px system-ui;color:#6a4fc2}
img{vertical-align:middle;max-width:100%}section{border-bottom:1px solid #ddd;padding-bottom:8px}
</style></head><body>
<h1>TS ${esc(data.spec)} — v${data.old} → v${data.new}</h1>
<p>${data.clauses.length} clauses changed · ${data.removed.length} removed · ${data.crs.length} CRs</p>
<h2>CRs</h2><table><tr><th>Version</th><th>CR</th><th>Cat</th><th>TDoc</th><th>Subject</th><th>Clauses affected</th></tr>${crRows}</table>
<h2>Changes</h2>${body}
${KATEX_JS}
<script>document.querySelectorAll("span.math").forEach(function(e){try{katex.render(e.textContent,e,{throwOnError:false,displayMode:e.classList.contains("display")})}catch(_){}})</script>
<p style="color:#888;font-size:12px">Generated by spec-viewer</p></body></html>`;
}

export function download(name: string, content: string, type = "text/html") {
  const a = document.createElement("a");
  a.href = URL.createObjectURL(new Blob([content], { type }));
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 1000);
}

