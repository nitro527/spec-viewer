function page(title: string, body: string): string {
  return `<!doctype html><html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>${KATEX_CSS}
<style>${AI_CSS}</style></head><body>${body}<p class="meta">Generated by spec-viewer · ${new Date().toLocaleString()}</p></body></html>`;
}

function sourceLine(tag: string, s: ChatSource): string {
  if (s.type === "cr") return `<li>${esc(tag)} — ${esc(s.title)} (<a href="${tdocUrl(s.tdoc)}">${esc(s.tdoc)}</a>)</li>`;
  if (s.type === "clause") return `<li>${esc(tag)} — ${esc(s.title)}</li>`;
  return `<li>${esc(tag)}</li>`;
}

function usedSources(m: ChatMessage): [string, ChatSource][] {
  const used = new Set([...m.content.matchAll(/\[\[([^\]]+)\]\]/g)].flatMap((x) => expandTag(x[1].trim(), m.sources ?? {})));
  return Object.entries(m.sources ?? {}).filter(([t]) => used.has(t));
}

/** One question and its answer, or a whole conversation, as a self-contained HTML page. */
export function chatHtml(title: string, messages: ChatMessage[]): string {
  const parts = messages.map((m) => {
    if (m.role === "user") {
      const ctx = m.context ? `<div class="ctx">TS ${esc(m.context.spec)} §${esc(m.context.clause ?? "")}${m.context.version ? ` v${esc(m.context.version)}` : ""} 에 대해</div>` : "";
      return `<h2>질문</h2>${ctx}<div class="q">${esc(m.content)}</div>`;
    }
    const src = usedSources(m);
    return `<div class="answer">${renderAnswer(m.content, m.sources ?? {})}</div>`
      + (src.length ? `<div class="sources"><b>출처</b><ul>${src.map(([t, s]) => sourceLine(t, s)).join("")}</ul></div>` : "")
      + (m.model ? `<p class="meta">${esc(m.model)} · AI 답변은 출처의 원문으로 확인하세요</p>` : "");
  });
  return page(title, `<h1>${esc(title)}</h1>${parts.join("\n")}`);
}

/** The answer as markdown with its sources listed (for pasting into mail, wiki, chat). */
export function answerMarkdown(question: string | undefined, m: ChatMessage): string {
  const src = usedSources(m).map(([t, s]) => `- ${t}${s.type !== "wi" ? ` — ${s.title}` : ""}${s.type === "cr" ? ` (${s.tdoc})` : ""}`);
  return `${question ? `**Q. ${question}**\n\n` : ""}${m.content}${src.length ? `\n\n출처:\n${src.join("\n")}` : ""}\n`;
}

export function releaseNoteMarkdown(spec: string, oldV: string, newV: string, n: ReleaseNote): string {
  const lines = [`# TS ${spec} v${oldV} → v${newV} 릴리즈 노트`, "", n.overview, ""];
  if (n.features.length) {
    lines.push("## 기능 추가·변경 (WI 별)", "");
    n.features.forEach((f) => lines.push(`- **${f.wi}** — ${f.what} (CR ${f.crs}; §${f.clauses})`));
    lines.push("");
  }
  if (n.corrections.length) {
    lines.push("## 주요 수정", "");
    n.corrections.forEach((c) => lines.push(`- ${c.what} (CR ${c.crs}; §${c.clauses})`));
    lines.push("");
  }
  if (n.impact) lines.push("## 구현 영향", "", n.impact, "");
  lines.push(`_CR ${n.crs}개 (AI 분석 ${n.analysed}개) 기준 · ${n.model ?? ""} · 신뢰도 ${n.confidence}_`);
  return lines.join("\n");
}

export function releaseNoteHtml(spec: string, oldV: string, newV: string, n: ReleaseNote): string {
  return page(`TS ${spec} v${oldV} → v${newV} 릴리즈 노트`, renderAnswer(releaseNoteMarkdown(spec, oldV, newV, n), {}));
}

/** The CR list as CSV for Excel: one row per CR with its cover and AI analysis. A BOM so Excel reads UTF-8
 *  (Korean analyses); formula-like cells are prefixed so a subject starting with "=" is not run as a formula. */
export function crCsv(rows: { cr: CR; analysis?: CRAnalysis }[]): string {
  const cell = (v: unknown) => {
    let s = String(v ?? "").replace(/\r?\n/g, " ");
    if (/^[=+@\t]|^-./.test(s)) s = `'${s}`;  // a lone "-" (no revision) is no formula
    return /[",]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  const head = ["Version", "CR", "Rev", "Cat", "Subject", "Release", "WI", "Meeting", "TDoc", "WG TDoc",
    "Clauses affected", "Reason for change", "Summary of change", "AI summary", "AI decision", "AI impact", "Link"];
  const lines = rows.map(({ cr: c, analysis: a }) => [
    c.new_version, c.cr, c.rev, c.cat, c.subject, c.detail?.release, c.detail?.wi_code, c.meeting, c.tdoc,
    c.detail?.wg_tdoc, c.detail?.clauses_raw, c.detail?.reason, c.detail?.summary, a?.summary, a?.decision, a?.impact,
    tdocUrl(c.tdoc),
  ].map(cell).join(","));
  return "﻿" + [head.join(","), ...lines].join("\r\n");
}
